package fr.openbook.api.importing;

import fr.openbook.api.importing.model.BookmoryReadTimer;
import fr.openbook.api.importing.service.BookmoryDbService;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.SingleConnectionDataSource;

import java.time.Instant;
import java.util.List;
import java.util.Map;

import static org.junit.jupiter.api.Assertions.*;

class BookmoryReadingCycleImportTest {

    @Test
    void createsCyclesAndAttachesSessionsIdempotently() {
        SingleConnectionDataSource ds = new SingleConnectionDataSource(
                "jdbc:h2:mem:bookmory_cycle_test;MODE=PostgreSQL;DATABASE_TO_LOWER=TRUE;DB_CLOSE_DELAY=-1",
                "sa",
                "",
                true
        );
        try {
            JdbcTemplate jdbc = new JdbcTemplate(ds);
            jdbc.execute("DROP TABLE IF EXISTS reading_session");
            jdbc.execute("DROP TABLE IF EXISTS reading_cycle");
            jdbc.execute("""
                CREATE TABLE reading_cycle (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id INTEGER NOT NULL,
                    book_id INTEGER NOT NULL,
                    is_common BOOLEAN NOT NULL DEFAULT FALSE,
                    started_at TIMESTAMP NOT NULL,
                    ended_at TIMESTAMP,
                    created_at TIMESTAMP NOT NULL,
                    updated_at TIMESTAMP NOT NULL
                )
            """);
            jdbc.execute("""
                CREATE TABLE reading_session (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id INTEGER NOT NULL,
                    book_id INTEGER NOT NULL,
                    reading_cycle_id INTEGER NOT NULL,
                    current_page INTEGER NOT NULL,
                    minutes_read INTEGER NOT NULL,
                    seconds_read INTEGER NOT NULL DEFAULT 0,
                    session_type INTEGER NOT NULL DEFAULT 1,
                    created_at TIMESTAMP NOT NULL
                )
            """);

            BookmoryDbService dbService = new BookmoryDbService(jdbc, null);

            Instant start1 = Instant.parse("2025-06-01T10:00:00Z");
            Instant timer1Time = Instant.parse("2025-06-02T20:00:00Z");
            Instant end1 = Instant.parse("2025-06-04T21:00:00Z");

            Long cycle1Id = dbService.findOrCreateReadingCycle(1L, 100L, start1, end1, false);
            assertNotNull(cycle1Id);
            assertTrue(dbService.ensureReadingStartSession(1L, 100L, cycle1Id, start1));

            BookmoryReadTimer timer1 = new BookmoryReadTimer();
            timer1.setElapsedSec(1830);
            timer1.setReadStartedAt(timer1Time.toEpochMilli());
            assertTrue(dbService.importReadingSession(1L, 100L, cycle1Id, timer1, 120));
            assertTrue(dbService.importReadingSessionAt(1L, 100L, cycle1Id, 300, 0, 0, 2, end1));

            // Second reading cycle (ongoing)
            Instant start2 = Instant.parse("2026-11-01T08:00:00Z");
            Instant timer2Time = Instant.parse("2026-11-03T19:30:00Z");
            Long cycle2Id = dbService.findOrCreateReadingCycle(1L, 100L, start2, null, false);
            assertNotNull(cycle2Id);
            assertNotEquals(cycle1Id, cycle2Id);
            assertTrue(dbService.ensureReadingStartSession(1L, 100L, cycle2Id, start2));

            BookmoryReadTimer timer2 = new BookmoryReadTimer();
            timer2.setElapsedSec(900);
            timer2.setReadStartedAt(timer2Time.toEpochMilli());
            assertTrue(dbService.importReadingSession(1L, 100L, cycle2Id, timer2, 45));

            // Re-importing should be idempotent
            Long cycle1Again = dbService.findOrCreateReadingCycle(1L, 100L, start1, end1, false);
            assertEquals(cycle1Id, cycle1Again);
            assertFalse(dbService.ensureReadingStartSession(1L, 100L, cycle1Again, start1));
            assertFalse(dbService.importReadingSession(1L, 100L, cycle1Again, timer1, 120));

            List<Map<String, Object>> cycles = jdbc.queryForList(
                    "SELECT id, is_common, started_at, ended_at FROM reading_cycle ORDER BY id ASC"
            );
            assertEquals(2, cycles.size());
            assertNotNull(cycles.get(0).get("ended_at"));
            assertNull(cycles.get(1).get("ended_at"));

            Integer c1Sessions = jdbc.queryForObject(
                    "SELECT COUNT(*) FROM reading_session WHERE reading_cycle_id = ?",
                    Integer.class,
                    cycle1Id
            );
            Integer c2Sessions = jdbc.queryForObject(
                    "SELECT COUNT(*) FROM reading_session WHERE reading_cycle_id = ?",
                    Integer.class,
                    cycle2Id
            );
            assertEquals(3, c1Sessions);
            assertEquals(2, c2Sessions);
        } finally {
            ds.destroy();
        }
    }
}
