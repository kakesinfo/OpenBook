package fr.openbook.api.migration;

import org.junit.jupiter.api.Test;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.Statement;
import java.sql.Timestamp;
import java.time.Instant;
import java.util.ArrayList;
import java.util.List;

import static org.junit.jupiter.api.Assertions.*;

class MigrateReadingSessionsToCyclesChangeTest {

    private record CycleRow(int id, int userId, int bookId, boolean isCommon, Timestamp startedAt, Timestamp endedAt) {}

    @Test
    void migratesSessionsIntoCyclesAndTransfersIsCommon() throws Exception {
        String url = "jdbc:h2:mem:migrate_cycles_test;MODE=PostgreSQL;DATABASE_TO_LOWER=TRUE;DB_CLOSE_DELAY=-1";
        try (Connection conn = DriverManager.getConnection(url, "sa", "");
             Statement st = conn.createStatement()) {

            st.execute("DROP TABLE IF EXISTS reading_session");
            st.execute("DROP TABLE IF EXISTS reading_cycle");

            st.execute("""
                CREATE TABLE reading_cycle (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id INTEGER NOT NULL,
                    book_id INTEGER NOT NULL,
                    is_common BOOLEAN NOT NULL DEFAULT FALSE,
                    started_at TIMESTAMP NOT NULL,
                    ended_at TIMESTAMP,
                    created_at TIMESTAMP NOT NULL,
                    updated_at TIMESTAMP NOT NULL
                )
            """);

            st.execute("""
                CREATE TABLE reading_session (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id INTEGER NOT NULL,
                    book_id INTEGER NOT NULL,
                    reading_cycle_id INTEGER,
                    current_page INTEGER NOT NULL,
                    minutes_read INTEGER NOT NULL,
                    seconds_read INTEGER NOT NULL DEFAULT 0,
                    session_type INTEGER NOT NULL DEFAULT 1,
                    is_common BOOLEAN NOT NULL DEFAULT FALSE,
                    created_at TIMESTAMP NOT NULL
                )
            """);

            // User 1, Book 10:
            // Cycle 1 (common, completed): start -> progress -> end
            Timestamp t1 = Timestamp.from(Instant.parse("2026-01-01T10:00:00Z"));
            Timestamp t2 = Timestamp.from(Instant.parse("2026-01-02T20:00:00Z"));
            Timestamp t3 = Timestamp.from(Instant.parse("2026-01-05T21:00:00Z"));
            insertSession(conn, 1, 10, 0, 0, 0, true, t1);
            insertSession(conn, 1, 10, 120, 45, 1, false, t2);
            insertSession(conn, 1, 10, 300, 60, 2, false, t3);

            // Cycle 2 (not common, ongoing): start -> progress
            Timestamp t4 = Timestamp.from(Instant.parse("2026-11-01T09:00:00Z"));
            Timestamp t5 = Timestamp.from(Instant.parse("2026-11-02T18:00:00Z"));
            insertSession(conn, 1, 10, 0, 0, 0, false, t4);
            insertSession(conn, 1, 10, 50, 20, 1, false, t5);

            // User 1, Book 20: orphan progress sessions without start/end
            Timestamp t6 = Timestamp.from(Instant.parse("2026-03-10T12:00:00Z"));
            Timestamp t7 = Timestamp.from(Instant.parse("2026-03-11T12:00:00Z"));
            insertSession(conn, 1, 20, 30, 15, 1, false, t6);
            insertSession(conn, 1, 20, 80, 25, 1, false, t7);

            // User 2, Book 10: older unclosed cycle before a new common start
            Timestamp t8 = Timestamp.from(Instant.parse("2026-04-01T10:00:00Z"));
            Timestamp t9 = Timestamp.from(Instant.parse("2026-04-02T10:00:00Z"));
            Timestamp t10 = Timestamp.from(Instant.parse("2026-05-01T10:00:00Z"));
            insertSession(conn, 2, 10, 0, 0, 0, false, t8);
            insertSession(conn, 2, 10, 40, 10, 1, false, t9);
            insertSession(conn, 2, 10, 0, 0, 0, true, t10);

            int created = MigrateReadingSessionsToCyclesChange.migrateConnection(conn);
            assertEquals(5, created);

            // Verify zero sessions have NULL reading_cycle_id
            try (ResultSet rs = st.executeQuery("SELECT COUNT(*) FROM reading_session WHERE reading_cycle_id IS NULL")) {
                assertTrue(rs.next());
                assertEquals(0, rs.getInt(1));
            }

            // Inspect created cycles
            List<CycleRow> cycles = new ArrayList<>();
            try (ResultSet rs = st.executeQuery(
                    "SELECT id, user_id, book_id, is_common, started_at, ended_at FROM reading_cycle ORDER BY id ASC"
            )) {
                while (rs.next()) {
                    cycles.add(new CycleRow(
                            rs.getInt("id"),
                            rs.getInt("user_id"),
                            rs.getInt("book_id"),
                            rs.getBoolean("is_common"),
                            rs.getTimestamp("started_at"),
                            rs.getTimestamp("ended_at")
                    ));
                }
            }

            assertEquals(5, cycles.size());

            // Cycle 1: user 1, book 10, common=true, started t1, ended t3, 3 sessions
            CycleRow c1 = cycles.get(0);
            assertEquals(1, c1.userId());
            assertEquals(10, c1.bookId());
            assertTrue(c1.isCommon());
            assertEquals(t1, c1.startedAt());
            assertEquals(t3, c1.endedAt());
            assertEquals(3, countSessionsInCycle(conn, c1.id()));

            // Cycle 2: user 1, book 10, common=false, started t4, ended null, 2 sessions
            CycleRow c2 = cycles.get(1);
            assertEquals(1, c2.userId());
            assertEquals(10, c2.bookId());
            assertFalse(c2.isCommon());
            assertEquals(t4, c2.startedAt());
            assertNull(c2.endedAt());
            assertEquals(2, countSessionsInCycle(conn, c2.id()));

            // Cycle 3: user 1, book 20, orphan progress sessions -> started t6, ended null, 2 sessions
            CycleRow c3 = cycles.get(2);
            assertEquals(1, c3.userId());
            assertEquals(20, c3.bookId());
            assertFalse(c3.isCommon());
            assertEquals(t6, c3.startedAt());
            assertNull(c3.endedAt());
            assertEquals(2, countSessionsInCycle(conn, c3.id()));

            // Cycle 4: user 2, book 10, older unclosed cycle -> started t8, ended null, common=false, 2 sessions
            CycleRow c4 = cycles.get(3);
            assertEquals(2, c4.userId());
            assertEquals(10, c4.bookId());
            assertFalse(c4.isCommon());
            assertEquals(t8, c4.startedAt());
            assertNull(c4.endedAt());
            assertEquals(2, countSessionsInCycle(conn, c4.id()));

            // Cycle 5: user 2, book 10, new common start -> started t10, ended null, common=true, 1 session
            CycleRow c5 = cycles.get(4);
            assertEquals(2, c5.userId());
            assertEquals(10, c5.bookId());
            assertTrue(c5.isCommon());
            assertEquals(t10, c5.startedAt());
            assertNull(c5.endedAt());
            assertEquals(1, countSessionsInCycle(conn, c5.id()));

            // Running migration again should be a no-op
            assertEquals(0, MigrateReadingSessionsToCyclesChange.migrateConnection(conn));
        }
    }

    @Test
    void keepsLeadingProgressSessionBeforeStartInSameCycleAndMergesOrphans() throws Exception {
        String url = "jdbc:h2:mem:merge_leading_progress_test;MODE=PostgreSQL;DATABASE_TO_LOWER=TRUE;DB_CLOSE_DELAY=-1";
        try (Connection conn = DriverManager.getConnection(url, "sa", "");
             Statement st = conn.createStatement()) {

            st.execute("DROP TABLE IF EXISTS reading_session");
            st.execute("DROP TABLE IF EXISTS reading_cycle");

            st.execute("""
                CREATE TABLE reading_cycle (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id INTEGER NOT NULL,
                    book_id INTEGER NOT NULL,
                    is_common BOOLEAN NOT NULL DEFAULT FALSE,
                    started_at TIMESTAMP NOT NULL,
                    ended_at TIMESTAMP,
                    created_at TIMESTAMP NOT NULL,
                    updated_at TIMESTAMP NOT NULL
                )
            """);

            st.execute("""
                CREATE TABLE reading_session (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id INTEGER NOT NULL,
                    book_id INTEGER NOT NULL,
                    reading_cycle_id INTEGER,
                    current_page INTEGER NOT NULL,
                    minutes_read INTEGER NOT NULL,
                    seconds_read INTEGER NOT NULL DEFAULT 0,
                    session_type INTEGER NOT NULL DEFAULT 1,
                    is_common BOOLEAN NOT NULL DEFAULT FALSE,
                    created_at TIMESTAMP NOT NULL
                )
            """);

            // Bookmory pattern: timer started 30m before read.start
            Timestamp t1 = Timestamp.from(Instant.parse("2026-03-01T10:00:00Z"));
            Timestamp t2 = Timestamp.from(Instant.parse("2026-03-01T10:30:00Z"));
            Timestamp t3 = Timestamp.from(Instant.parse("2026-03-02T20:00:00Z"));
            insertSession(conn, 1, 99, 45, 30, 1, false, t1);
            insertSession(conn, 1, 99, 0, 0, 0, false, t2);
            insertSession(conn, 1, 99, 200, 60, 2, false, t3);

            int created = MigrateReadingSessionsToCyclesChange.migrateConnection(conn);
            assertEquals(1, created);

            // Also verify MergeLeadingOrphanProgressCyclesChange merges an already-split pair
            st.execute("INSERT INTO reading_cycle (id, user_id, book_id, is_common, started_at, ended_at, created_at, updated_at) " +
                    "VALUES (500, 2, 88, FALSE, TIMESTAMP '2026-04-01 10:00:00', NULL, TIMESTAMP '2026-04-01 10:00:00', TIMESTAMP '2026-04-01 10:00:00')");
            st.execute("INSERT INTO reading_cycle (id, user_id, book_id, is_common, started_at, ended_at, created_at, updated_at) " +
                    "VALUES (501, 2, 88, TRUE, TIMESTAMP '2026-04-01 10:30:00', TIMESTAMP '2026-04-02 20:00:00', TIMESTAMP '2026-04-01 10:30:00', TIMESTAMP '2026-04-02 20:00:00')");
            st.execute("INSERT INTO reading_session (user_id, book_id, reading_cycle_id, current_page, minutes_read, seconds_read, session_type, is_common, created_at) " +
                    "VALUES (2, 88, 500, 30, 25, 0, 1, FALSE, TIMESTAMP '2026-04-01 10:00:00')");
            st.execute("INSERT INTO reading_session (user_id, book_id, reading_cycle_id, current_page, minutes_read, seconds_read, session_type, is_common, created_at) " +
                    "VALUES (2, 88, 501, 0, 0, 0, 0, TRUE, TIMESTAMP '2026-04-01 10:30:00')");
            st.execute("INSERT INTO reading_session (user_id, book_id, reading_cycle_id, current_page, minutes_read, seconds_read, session_type, is_common, created_at) " +
                    "VALUES (2, 88, 501, 200, 40, 0, 2, FALSE, TIMESTAMP '2026-04-02 20:00:00')");

            int merged = MergeLeadingOrphanProgressCyclesChange.mergeConnection(conn);
            assertEquals(1, merged);
            assertEquals(3, countSessionsInCycle(conn, 501));
            assertEquals(0, countSessionsInCycle(conn, 500));
        }
    }

    private static void insertSession(
            Connection conn,
            int userId,
            int bookId,
            int currentPage,
            int minutesRead,
            int sessionType,
            boolean isCommon,
            Timestamp createdAt
    ) throws Exception {
        try (PreparedStatement ps = conn.prepareStatement(
                "INSERT INTO reading_session (user_id, book_id, current_page, minutes_read, seconds_read, session_type, is_common, created_at) " +
                "VALUES (?, ?, ?, ?, 0, ?, ?, ?)"
        )) {
            ps.setInt(1, userId);
            ps.setInt(2, bookId);
            ps.setInt(3, currentPage);
            ps.setInt(4, minutesRead);
            ps.setInt(5, sessionType);
            ps.setBoolean(6, isCommon);
            ps.setTimestamp(7, createdAt);
            ps.executeUpdate();
        }
    }

    private static int countSessionsInCycle(Connection conn, int cycleId) throws Exception {
        try (PreparedStatement ps = conn.prepareStatement(
                "SELECT COUNT(*) FROM reading_session WHERE reading_cycle_id = ?"
        )) {
            ps.setInt(1, cycleId);
            try (ResultSet rs = ps.executeQuery()) {
                assertTrue(rs.next());
                return rs.getInt(1);
            }
        }
    }
}
